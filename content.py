def get_progress_bar(current, total, length=15):
    """إنشاء شريط تقدم مرئي"""
    filled = int(length * current / total) if total > 0 else 0
    empty = length - filled
    bar = "█" * filled + "░" * empty
    percentage = int(100 * current / total) if total > 0 else 0
    return f"[{bar}] {percentage}%"
